"""`heulistic init` — write a starter config sized to this machine.

A generic sample config is a poor first experience: the usual failure is an
OOM twenty minutes in, because the example assumed a bigger card. Since the
CLI can already see the local GPU and estimate VRAM, the starter config picks
a model that actually fits.
"""

from __future__ import annotations

from pathlib import Path
from typing import Optional

import typer

from . import gpu
from ._deps import require_axolotl


def validate(config_yaml):
    return require_axolotl().validate(config_yaml)


def vram_required_gb(config):
    return require_axolotl().vram.vram_required_gb(config)

# QLoRA-friendly models, smallest first. The largest entry that fits the card
# wins.
#
# The ladder deliberately stops at 8B rather than climbing to 70B. This is a
# starter config: the goal is a run that finishes quickly and works, not one
# that fills the GPU. Someone with an 80 GB card can pass --model.
_LADDER = [
    "Qwen/Qwen2.5-0.5B",
    "Qwen/Qwen2.5-1.5B",
    "Qwen/Qwen2.5-3B",
    "Qwen/Qwen2.5-7B",
]
# Every entry must be ungated. The ladder previously led with Llama-3.2, which
# is gated on the Hub — so the first `heulistic train` after `init` was rejected
# for want of an approved HuggingFace token, which is precisely the wall `init`
# exists to avoid. Qwen2.5 is Apache-2.0 and needs no token.
_FALLBACK_MODEL = "Qwen/Qwen2.5-0.5B"

# Leave room for activations, fragmentation and the desktop's own usage.
_USABLE_FRACTION = 0.75


def _template(base_model: str) -> dict:
    """A complete, warning-free QLoRA config.

    Every field the validator would otherwise flag as missing is set
    explicitly, so `heulistic validate-config` on a freshly generated file is
    silent — a starter config that immediately complains teaches the wrong
    thing.
    """
    return {
        "base_model": base_model,
        "adapter": "qlora",
        "load_in_4bit": True,
        "datasets": [{"path": "tatsu-lab/alpaca", "type": "alpaca"}],
        "sequence_len": 1024,
        "micro_batch_size": 1,
        "gradient_accumulation_steps": 8,
        "num_epochs": 1,
        "learning_rate": 0.0002,
        "lora_r": 16,
        "lora_alpha": 32,
        "lora_dropout": 0.05,
        "lora_target_linear": True,
        "bf16": "auto",
        "gradient_checkpointing": True,
        "save_steps": 100,
        "val_set_size": 0.05,
        "output_dir": "./outputs",
    }


def _describe_vram(hardware) -> str:
    if hardware.gpu_count == 1:
        return f"{hardware.total_vram_gb:g} GB"
    return f"{hardware.gpu_count} x {hardware.per_gpu_vram_gb:g} GB"


def _pick_model(budget_gb: float | None) -> str:
    """Largest model from the ladder that fits the budget."""
    if budget_gb is None:
        return _FALLBACK_MODEL
    chosen = None
    for model in _LADDER:
        if vram_required_gb(_template(model)) <= budget_gb:
            chosen = model
    return chosen or _LADDER[0]


def _render(config: dict) -> str:
    """Emit YAML by hand, so the file is commented and ordered for a human."""
    import yaml

    header = (
        "# Generated by `heulistic init`.\n"
        "# Check it before training:  heulistic validate-config config.yaml\n"
        "# Then run it:               heulistic train config.yaml\n\n"
    )
    return header + yaml.safe_dump(config, sort_keys=False, default_flow_style=False)


def init(
    output: Path = typer.Option(
        Path("config.yaml"), "--output", "-o", help="Where to write the config."
    ),
    model: Optional[str] = typer.Option(
        None, "--model", "-m", help="Base model to use instead of the auto-picked one."
    ),
    force: bool = typer.Option(False, "--force", "-f", help="Overwrite an existing file."),
) -> None:
    """Write a starter Axolotl config, sized to the local GPU."""
    if output.exists() and not force:
        typer.secho(f"{output} already exists — pass --force to overwrite.",
                    fg=typer.colors.RED)
        raise typer.Exit(code=1)

    hardware = gpu.detect_hardware()
    if hardware is None:
        typer.secho(
            "No NVIDIA GPU detected — writing a small starter config. "
            "Use --model to choose another.",
            fg=typer.colors.YELLOW,
        )
        budget = None
    else:
        # QLoRA is never sharded, so every card must hold the whole model.
        budget = hardware.per_gpu_vram_gb * _USABLE_FRACTION
        typer.echo(
            f"Detected {hardware.label} ({_describe_vram(hardware)}) — "
            f"sizing for roughly {budget:.0f} GB of usable VRAM per GPU."
        )

    base_model = model or _pick_model(budget)
    config = _template(base_model)
    required = vram_required_gb(config)

    if model and hardware is not None and required > hardware.per_gpu_vram_gb:
        typer.secho(
            f"  Warning: {model} needs roughly {required:.0f} GB of VRAM per GPU but "
            f"{hardware.label} has {_describe_vram(hardware)}.",
            fg=typer.colors.YELLOW,
        )

    output.write_text(_render(config))

    typer.secho(f"Wrote {output}", fg=typer.colors.GREEN)
    typer.echo(f"  model: {base_model}  (~{required:.1f} GB VRAM as QLoRA)")
    typer.echo(f"  data:  tatsu-lab/alpaca — swap in your own under 'datasets'")
    typer.echo()
    typer.echo(f"Next:  heulistic train {output}")

    # Never ship a starter file our own validator would complain about.
    problems = [d for d in validate(output.read_text()) if d.level in ("error", "warning")]
    if problems:  # pragma: no cover - guards against template drift
        typer.secho(
            f"  ({len(problems)} validator finding(s) in the generated file — "
            "please report this)",
            fg=typer.colors.YELLOW,
        )
