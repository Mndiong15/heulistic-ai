"""The generated schema module.

The generated `_schema_data.py` is committed and regenerated by hand, so the
first test here is the one that matters: it fails if the reference was edited
without re-running the generator.
"""

from heulistic_axolotl._reference import parse_reference
from heulistic_axolotl.generate import render
from heulistic_axolotl.reference import reference_text
from heulistic_axolotl.schema import (
    SCHEMA,
    get_field,
    get_model,
    is_known_field,
    known_field_names,
)


def test_generated_schema_is_up_to_date():
    """Fails when reference/axolotl.yaml changed but the schema wasn't regenerated.

    Fix by running:  python -m heulistic_axolotl.generate
    """
    from pathlib import Path

    import heulistic_axolotl

    committed = (
        Path(heulistic_axolotl.__file__).parent / "_schema_data.py"
    ).read_text(encoding="utf-8")
    expected = render(parse_reference(reference_text()))
    assert committed == expected, (
        "Generated schema is stale — run: python -m heulistic_axolotl.generate"
    )


def test_schema_matches_the_reference_shape():
    reference = parse_reference(reference_text())
    assert SCHEMA.field_count == reference.field_count
    assert SCHEMA.total_field_count == reference.total_field_count
    assert set(SCHEMA.subschemas) == set(reference.subschemas)
    assert SCHEMA.consumed_field_lines == reference.consumed_field_lines


def test_types_survive_the_round_trip():
    # Types are re-parsed from the generated raw strings, so confirm the
    # reconstructed behaviour still matches the reference's.
    reference = parse_reference(reference_text())
    for name, field in reference.fields.items():
        assert SCHEMA.fields[name].type == field.type, name


def test_defaults_and_docs_survive_the_round_trip():
    reference = parse_reference(reference_text())
    for name, field in reference.fields.items():
        rebuilt = SCHEMA.fields[name]
        assert rebuilt.default == field.default, name
        assert type(rebuilt.default) is type(field.default), name
        assert rebuilt.doc == field.doc, name
        assert rebuilt.required == field.required, name


# ── Lookup helpers ────────────────────────────────────────────────────────────

def test_get_field():
    assert get_field("micro_batch_size") is not None
    assert get_field("micro_batch_size").type.accepts(4) is True
    assert get_field("no_such_option") is None


def test_is_known_field_catches_typos():
    assert is_known_field("learning_rate") is True
    # Aliases people actually write — the validator turns these into hints.
    assert is_known_field("lr") is False
    assert is_known_field("epochs") is False
    assert is_known_field("model") is False


def test_known_field_names_is_the_full_top_level_set():
    assert len(known_field_names()) == SCHEMA.field_count
    assert "base_model" in known_field_names()
    # Nested fields are not top-level fields.
    assert "system_prompt" not in known_field_names()


def test_get_model():
    sft = get_model("SFTDataset")
    assert sft is not None
    assert "path" in sft.fields
    assert get_model("NotAModel") is None
